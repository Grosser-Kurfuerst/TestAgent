def _plan_task_response(task_type: str, turn: int) -> ChatResponse:
    if task_type == "inspect":
        if turn == 1:
            return _tool_chat_response("retrieve_context", {"query": "subtract", "top_k": 3})
        if turn == 2:
            return _tool_chat_response("read_file", {"path": "calculator.py", "limit": 12000})
        return _tool_chat_response("finish", {"summary": "Inspected calculator implementation and tests."})

    if task_type == "edit":
        if turn == 1:
            return _tool_chat_response("read_file", {"path": "calculator.py", "limit": 12000})
        if turn == 2:
            old = 'def subtract(a: int, b: int) -> int:\n    """Return a minus b."""\n    return a + b'
            new = 'def subtract(a: int, b: int) -> int:\n    """Return a minus b."""\n    return a - b'
            return _tool_chat_response("replace_in_file", {"path": "calculator.py", "old": old, "new": new})
        if turn == 3:
            return _tool_chat_response("run_tests", {})
        return _tool_chat_response(
            "finish",
            {"summary": "Updated subtract to return the first number minus the second number and ran tests."},
        )

    if task_type == "test":
        if turn == 1:
            return _tool_chat_response("run_tests", {})
        return _tool_chat_response("finish", {"summary": "Ran the configured tests."})

    if turn == 1:
        return _tool_chat_response("retrieve_context", {"query": "subtract", "top_k": 3})
    if turn == 2:
        return _tool_chat_response("read_file", {"path": "calculator.py", "limit": 12000})
    return _tool_chat_response("finish", {"summary": "Completed the plan task."})


def _plan_task_key(messages: list[MessageLike]) -> tuple[str, str] | None:
    text = _messages_text(messages)
    task_id = _line_value(text, "Current task id:")
    task_type = _line_value(text, "Current task type:")
    if not task_id and "Current step:" in text:
        task_id = _line_value(text, "- id:")
        task_type = _line_value(text, "- type:")
    if not task_id:
        return None
    return task_id, (task_type or "analysis").strip().lower()


def _line_value(text: str, prefix: str) -> str:
    for line in text.splitlines():
        if line.startswith(prefix):
            return line.removeprefix(prefix).strip()
    return ""


def _is_team_planner_prompt(messages: list[MessageLike]) -> bool:
    system_prompt = _first_system_message_text(messages).lower()
    return (
        "you are the planner in a multi-agent coding team" in system_prompt
        and "return only json with this shape" in system_prompt
        and '"steps"' in system_prompt
    )


def _is_team_reviewer_prompt(messages: list[MessageLike]) -> bool:
    system_prompt = _first_system_message_text(messages).lower()
    return (
        "you are a reviewer sub-agent in a multi-agent coding team" in system_prompt
        and "return only json with this shape" in system_prompt
        and '"approved"' in system_prompt
    )


def _first_system_message_text(messages: list[MessageLike]) -> str:
    for message in messages:
        role = ""
        content: object = ""
        if isinstance(message, dict):
            role = str(message.get("role", ""))
            content = message.get("content", "")
        else:
            role = message.role
            content = message.content
        if role == "system" and isinstance(content, str):
            return content
    return ""


def _messages_text(messages: list[MessageLike]) -> str:
    rendered: list[str] = []
    for message in messages:
        if isinstance(message, dict):
            content = message.get("content", "")
        else:
            content = message.content
        if isinstance(content, str):
            rendered.append(content)
    return "\n".join(rendered)


def _excerpt(text: str, limit: int = 500) -> str:
    return text if len(text) <= limit else text[:limit] + "\n... truncated"


