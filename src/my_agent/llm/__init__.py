def _fake_team_review_json(prompt_text: str) -> str:
    approved = "worker result:\nno worker result was provided" not in prompt_text
    summary = "FakeLLM reviewer approved the worker result." if approved else "FakeLLM reviewer found no worker result."
    issues = [] if approved else ["Worker result is empty."]
    return json.dumps({"approved": approved, "summary": summary, "issues": issues, "suggestions": []}, ensure_ascii=False)


